"""Check a commit message or pull request title against the subject format.

The format and the allowed types are described in `CONTRIBUTING.md`.
"""

import argparse
import re
import sys
from pathlib import Path

TYPES = ("feat", "fix", "refactor", "docs", "chore")
MAX_LENGTH = 72
SUBJECT_RE = re.compile(r"(?P<type>[a-z]+)(?:\([a-z0-9-]+\))?!?: \S")
# Subjects git generates itself, for merges, `git revert`, and
# `git commit --fixup/--squash`.
GIT_PREFIXES = ("Merge ", 'Revert "', "fixup! ", "squash! ", "amend! ")


def check_subject(subject: str) -> list[str]:
    """Checks a subject line.

    Args:
        subject: The subject line, or a pull request title.

    Returns:
        Error messages; empty if the subject is valid or generated by git.
    """
    if subject.startswith(GIT_PREFIXES):
        return []
    errors = []
    match = SUBJECT_RE.match(subject)
    if match is None:
        errors.append("does not match '<type>[(<scope>)][!]: <subject>'")
    elif match["type"] not in TYPES:
        errors.append(f"type '{match['type']}' is not one of {', '.join(TYPES)}")
    if len(subject) > MAX_LENGTH:
        errors.append(f"is {len(subject)} characters long, more than {MAX_LENGTH}")
    return errors


def subject_of(message: str) -> str:
    """Returns a commit message's subject line.

    Args:
        message: The full message. `#` comment lines are ignored, as git does.

    Returns:
        The first line that is neither blank nor a comment, or an empty string.
    """
    for line in message.splitlines():
        if line.strip() and not line.startswith("#"):
            return line
    return ""


def main(argv: list[str] | None = None) -> int:
    """Checks the subject given on the command line.

    Args:
        argv: The command-line arguments, without the program name.

    Returns:
        The process exit code.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument(
        "message_file",
        nargs="?",
        type=Path,
        help="a commit message file, as the commit-msg hook passes it",
    )
    source.add_argument("--title", help="a pull request title")
    args = parser.parse_args(argv)

    if args.title is not None:
        subject = args.title
    else:
        subject = subject_of(args.message_file.read_text())
    errors = check_subject(subject)
    for error in errors:
        print(f"Subject {subject!r} {error}.", file=sys.stderr)
    if errors:
        print("See 'Commits and pull requests' in CONTRIBUTING.md.", file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
